#!/usr/bin/env python3
"""
Phase 11: LaTeX Publication Tables Generator.
Produces clean, professional booktabs tables in results/:
- results/table_summary.tex: Main comparative performance matrix (Depth 6, P in {1, 2, 4, 8})
- results/table_failure.tex: Degradation under move ordering failure (Depth 6, P=8)
"""

import os
import sys
import pandas as pd
import numpy as np

def generate_table_summary(summary_csv_path="results/summary.csv", out_tex_path="results/table_summary.tex"):
    if not os.path.exists(summary_csv_path):
        print(f"Error: {summary_csv_path} not found.")
        return

    df = pd.read_csv(summary_csv_path)
    # Filter depth 6, midgame phase (canonical benchmark)
    sub = df[(df["depth"] == 6) & (df["phase"] == "mid")].sort_values(["algo", "threads"])

    algo_names = {
        "b2": "Sequential Alpha-Beta ($B_2$)",
        "p1": "Root Splitting ($P_1$)",
        "p2": "PVS ($P_2$)",
        "p3": "YBWC ($P_3$)"
    }

    lines = []
    lines.append("% Auto-generated by analysis/generate_latex_tables.py")
    lines.append("\\begin{table}[htbp]")
    lines.append("  \\centering")
    lines.append("  \\caption{Parallel Search Performance Matrix at Depth 6 (Midgame Phase, 30 Positions, 3 Repeats)}")
    lines.append("  \\label{tab:search_summary}")
    lines.append("  \\begin{tabular}{l c r r c c c c}")
    lines.append("    \\toprule")
    lines.append("    \\textbf{Algorithm} & \\textbf{Cores ($P$)} & \\textbf{Time (ms)} & \\textbf{Nodes} & \\textbf{Speedup ($S_P$)} & \\textbf{Efficiency ($E_P$)} & \\textbf{Overhead ($SO_P$)} & \\textbf{$B_2$ Match} \\\\")
    lines.append("    \\midrule")

    current_algo = None
    for _, row in sub.iterrows():
        algo = row["algo"]
        threads = int(row["threads"])
        time_ms = f"{row['avg_time_ms']:.2f} \\pm {row['std_time_ms']:.2f}"
        nodes = f"{int(row['avg_nodes']):,}"
        speedup = f"{row['speedup_mean']:.2f}\\times"
        eff = f"{row['efficiency_mean'] * 100.0:.1f}\\%"
        sop = f"{row['sop_mean'] * 100.0:+.1f}\\%" if algo != "p1" else "0.0\\%"
        match_pct = f"{row['value_agreement_pct']:.1f}\\%"

        if current_algo is not None and current_algo != algo:
            lines.append("    \\addlinespace")
        current_algo = algo

        algo_label = algo_names.get(algo, algo) if threads == 1 or (algo == "p1" and threads == 1) else ""
        lines.append(f"    {algo_label:<30} & {threads:<2} & {time_ms:<15} & {nodes:<10} & {speedup:<8} & {eff:<8} & {sop:<8} & {match_pct} \\\\")

    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("\\end{table}")

    os.makedirs(os.path.dirname(out_tex_path), exist_ok=True)
    with open(out_tex_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Saved: {out_tex_path}")

def generate_table_failure(failure_csv_path="results/failure.csv", out_tex_path="results/table_failure.tex"):
    if not os.path.exists(failure_csv_path):
        print(f"Error: {failure_csv_path} not found.")
        return

    df = pd.read_csv(failure_csv_path)
    sub = df[(df["depth"] == 6)]

    # Compute per-position metrics against B2
    pos_avg = sub.groupby(["algo", "order", "pos_id"]).agg(
        time_ms=("time_ms", "mean"),
        nodes=("nodes", "mean"),
        steals=("steals", "mean"),
        idle_us=("idle_us", "mean")
    ).reset_index()

    b2_base = pos_avg[pos_avg["algo"] == "b2"].set_index(["order", "pos_id"])

    def get_b2(row):
        key = (row["order"], row["pos_id"])
        if key in b2_base.index:
            return b2_base.loc[key, "time_ms"], b2_base.loc[key, "nodes"]
        return row["time_ms"], row["nodes"]

    b_vals = [get_b2(r) for _, r in pos_avg.iterrows()]
    pos_avg["t_b2"] = [b[0] for b in b_vals]
    pos_avg["n_b2"] = [b[1] for b in b_vals]
    pos_avg["speedup"] = pos_avg["t_b2"] / pos_avg["time_ms"].clip(lower=0.001)
    pos_avg["sop"] = (pos_avg["nodes"] / pos_avg["n_b2"].clip(lower=1.0)) - 1.0

    summary = pos_avg.groupby(["algo", "order"]).agg(
        avg_time_ms=("time_ms", "mean"),
        avg_nodes=("nodes", "mean"),
        speedup=("speedup", "mean"),
        sop=("sop", "mean"),
        steals=("steals", "mean"),
        idle_ms=("idle_us", lambda x: np.mean(x) / 1000.0)
    ).reset_index()

    order_names = {
        "full": "Full (TT + Corner + History + Mobility)",
        "history_only": "History Heuristic Only",
        "none": "Natural Bitboard Order (None)",
        "random": "Deterministic Pseudo-Random",
        "reverse": "Worst-First (Reverse Ordered)"
    }

    order_order = ["full", "history_only", "none", "random", "reverse"]

    lines = []
    lines.append("% Auto-generated by analysis/generate_latex_tables.py")
    lines.append("\\begin{table}[htbp]")
    lines.append("  \\centering")
    lines.append("  \\caption{Failure Analysis: Performance Breakdown Under Degraded Move Ordering at Depth 6 ($P=8$)}")
    lines.append("  \\label{tab:failure_analysis}")
    lines.append("  \\begin{tabular}{l l r r c c r}")
    lines.append("    \\toprule")
    lines.append("    \\textbf{Algorithm} & \\textbf{Ordering Regime} & \\textbf{Time (ms)} & \\textbf{Nodes} & \\textbf{Speedup ($S_8$)} & \\textbf{Overhead ($SO_8$)} & \\textbf{Idle (ms)} \\\\")
    lines.append("    \\midrule")

    for algo in ["b2", "p1", "p2", "p3"]:
        algo_label = {
            "b2": "$B_2$ (Seq $\\alpha\\beta$)",
            "p1": "$P_1$ (Root Split)",
            "p2": "$P_2$ (PVS)",
            "p3": "$P_3$ (YBWC)"
        }[algo]

        algo_data = summary[summary["algo"] == algo].set_index("order")
        is_first = True
        for o in order_order:
            if o not in algo_data.index:
                continue
            r = algo_data.loc[o]
            lbl = algo_label if is_first else ""
            is_first = False
            o_name = order_names.get(o, o)
            t_str = f"{r['avg_time_ms']:.2f}"
            n_str = f"{int(r['avg_nodes']):,}"
            s_str = f"{r['speedup']:.2f}\\times" if algo != "b2" else "1.00\\times"
            sop_str = f"{r['sop'] * 100.0:+.1f}\\%" if algo != "b2" else "---"
            idle_str = f"{r['idle_ms']:.1f}" if algo != "b2" else "0.0"
            lines.append(f"    {lbl:<25} & {o_name:<40} & {t_str:<8} & {n_str:<10} & {s_str:<8} & {sop_str:<8} & {idle_str} \\\\")
        lines.append("    \\addlinespace")

    # Remove trailing addlinespace
    if lines[-1] == "    \\addlinespace":
        lines.pop()

    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("\\end{table}")

    os.makedirs(os.path.dirname(out_tex_path), exist_ok=True)
    with open(out_tex_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Saved: {out_tex_path}")

def main():
    generate_table_summary()
    generate_table_failure()

if __name__ == "__main__":
    main()
